-- =====================================================================
-- Sabores Royal — Stock pro: costo, stock mínimo, historial de
-- movimientos e ingreso de mercadería desde la factura del proveedor.
-- =====================================================================
-- * product_admin: datos internos de cada producto (costo, stock mínimo,
--   proveedor habitual). Va en tabla aparte porque products es de lectura
--   pública (la usa la tienda): el costo NO tiene que verlo un cliente.
-- * stock_movements: historial de cada cambio de stock. Lo llena solo un
--   trigger sobre products.stock, así que registra también las ventas de
--   la caja, los pedidos online y las anulaciones sin tocar esas funciones.
-- * supplier_product_map: recuerda qué producto es cada renglón de la
--   factura de cada proveedor, para emparejarlo solo la próxima vez.
-- * stock_ingreso() / stock_ajuste(): aplican un ingreso de mercadería o
--   un ajuste (conteo) de forma atómica, dejando el motivo en el historial.
--
-- Seguro de correr más de una vez.
-- =====================================================================

CREATE TABLE IF NOT EXISTS product_admin (
  product_id      bigint PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
  cost            numeric(12,2),
  cost_updated_at timestamptz,
  min_stock       integer,
  supplier        text,
  updated_at      timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE product_admin ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admin product_admin" ON product_admin;
CREATE POLICY "Admin product_admin" ON product_admin FOR ALL USING (is_admin()) WITH CHECK (is_admin());

CREATE TABLE IF NOT EXISTS stock_movements (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  qty         integer NOT NULL,           -- + entra, - sale
  stock_after integer,
  kind        text NOT NULL,              -- venta | ingreso | conteo | ajuste | alta | edicion
  ref         text,                       -- N° de factura, etc.
  note        text,
  unit_cost   numeric(12,2),
  created_by  uuid,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_movements_product_idx ON stock_movements(product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS stock_movements_created_idx ON stock_movements(created_at DESC);
ALTER TABLE stock_movements ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admin read stock_movements" ON stock_movements;
CREATE POLICY "Admin read stock_movements" ON stock_movements FOR SELECT USING (is_admin());

CREATE TABLE IF NOT EXISTS supplier_product_map (
  proveedor_key  text NOT NULL,
  desc_key       text NOT NULL,
  product_id     bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  units_per_pack numeric NOT NULL DEFAULT 1,
  updated_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (proveedor_key, desc_key)
);
ALTER TABLE supplier_product_map ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admin supplier_product_map" ON supplier_product_map;
CREATE POLICY "Admin supplier_product_map" ON supplier_product_map FOR ALL USING (is_admin()) WITH CHECK (is_admin());

-- Historial automático: cada cambio de products.stock deja un movimiento.
-- El motivo lo marcan stock_ingreso()/stock_ajuste() con set_config; si no
-- hay marca (ventas de caja, pedidos, anulaciones, edición a mano) se
-- clasifica solo: baja = venta, sube = edición/anulación.
CREATE OR REPLACE FUNCTION log_stock_movement()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  v_kind text := nullif(current_setting('app.stock_kind', true), '');
  v_old  integer := CASE WHEN TG_OP = 'INSERT' THEN 0 ELSE coalesce(OLD.stock, 0) END;
BEGIN
  IF coalesce(NEW.stock, 0) = v_old THEN RETURN NEW; END IF;
  INSERT INTO stock_movements(product_id, qty, stock_after, kind, ref, note, unit_cost, created_by)
  VALUES (
    NEW.id, coalesce(NEW.stock, 0) - v_old, NEW.stock,
    coalesce(v_kind, CASE WHEN TG_OP = 'INSERT' THEN 'alta' WHEN NEW.stock < v_old THEN 'venta' ELSE 'edicion' END),
    nullif(current_setting('app.stock_ref', true), ''),
    nullif(current_setting('app.stock_note', true), ''),
    nullif(current_setting('app.stock_cost', true), '')::numeric,
    auth.uid()
  );
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_log_stock_movement ON products;
CREATE TRIGGER trg_log_stock_movement
  AFTER INSERT OR UPDATE OF stock ON products
  FOR EACH ROW EXECUTE FUNCTION log_stock_movement();

-- Ingreso de mercadería. p_items: [{product_id, qty, unit_cost, update_cost,
-- desc_key, units_per_pack}] — qty y unit_cost ya por UNIDAD de venta.
CREATE OR REPLACE FUNCTION stock_ingreso(p_items jsonb, p_proveedor text, p_ref text, p_note text)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  v_item jsonb;
  v_n integer := 0;
  v_prov_key text := upper(trim(coalesce(p_proveedor, '')));
BEGIN
  IF NOT is_admin() THEN RAISE EXCEPTION 'solo_admin'; END IF;
  PERFORM set_config('app.stock_kind', 'ingreso', true);
  PERFORM set_config('app.stock_ref', coalesce(p_ref, ''), true);
  PERFORM set_config('app.stock_note', coalesce(nullif(p_note, ''), nullif(p_proveedor, ''), ''), true);
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    PERFORM set_config('app.stock_cost', coalesce(v_item->>'unit_cost', ''), true);
    UPDATE products SET stock = coalesce(stock, 0) + (v_item->>'qty')::int
      WHERE id = (v_item->>'product_id')::bigint;
    IF NOT FOUND THEN CONTINUE; END IF;
    v_n := v_n + 1;
    INSERT INTO product_admin(product_id, cost, cost_updated_at, supplier, updated_at)
    VALUES ((v_item->>'product_id')::bigint,
            CASE WHEN coalesce((v_item->>'update_cost')::boolean, false) THEN (v_item->>'unit_cost')::numeric END,
            CASE WHEN coalesce((v_item->>'update_cost')::boolean, false) THEN now() END,
            nullif(trim(coalesce(p_proveedor, '')), ''), now())
    ON CONFLICT (product_id) DO UPDATE SET
      cost = CASE WHEN coalesce((v_item->>'update_cost')::boolean, false) THEN (v_item->>'unit_cost')::numeric ELSE product_admin.cost END,
      cost_updated_at = CASE WHEN coalesce((v_item->>'update_cost')::boolean, false) THEN now() ELSE product_admin.cost_updated_at END,
      supplier = coalesce(nullif(trim(coalesce(p_proveedor, '')), ''), product_admin.supplier),
      updated_at = now();
    IF v_prov_key <> '' AND coalesce(v_item->>'desc_key', '') <> '' THEN
      INSERT INTO supplier_product_map(proveedor_key, desc_key, product_id, units_per_pack, updated_at)
      VALUES (v_prov_key, v_item->>'desc_key', (v_item->>'product_id')::bigint,
              coalesce((v_item->>'units_per_pack')::numeric, 1), now())
      ON CONFLICT (proveedor_key, desc_key) DO UPDATE SET
        product_id = EXCLUDED.product_id, units_per_pack = EXCLUDED.units_per_pack, updated_at = now();
    END IF;
  END LOOP;
  PERFORM set_config('app.stock_kind', '', true);
  PERFORM set_config('app.stock_cost', '', true);
  RETURN v_n;
END $$;

-- Ajuste de stock (conteo físico o corrección). p_items: [{product_id, stock}]
CREATE OR REPLACE FUNCTION stock_ajuste(p_items jsonb, p_kind text, p_note text)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE
  v_item jsonb;
  v_n integer := 0;
BEGIN
  IF NOT is_admin() THEN RAISE EXCEPTION 'solo_admin'; END IF;
  PERFORM set_config('app.stock_kind', CASE WHEN p_kind IN ('conteo', 'ajuste') THEN p_kind ELSE 'ajuste' END, true);
  PERFORM set_config('app.stock_note', coalesce(p_note, ''), true);
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    UPDATE products SET stock = (v_item->>'stock')::int
      WHERE id = (v_item->>'product_id')::bigint AND stock IS DISTINCT FROM (v_item->>'stock')::int;
    IF FOUND THEN v_n := v_n + 1; END IF;
  END LOOP;
  PERFORM set_config('app.stock_kind', '', true);
  RETURN v_n;
END $$;

REVOKE ALL ON FUNCTION stock_ingreso(jsonb, text, text, text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION stock_ajuste(jsonb, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION stock_ingreso(jsonb, text, text, text) TO authenticated;
GRANT EXECUTE ON FUNCTION stock_ajuste(jsonb, text, text) TO authenticated;
